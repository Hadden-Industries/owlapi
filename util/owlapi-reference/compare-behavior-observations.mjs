import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const provenanceRows = new Set([
  "runtime",
  "owlapi-origin",
  "api-origin",
  "source",
  "selected",
  "processor",
]);
const digest = (text) => createHash("sha256").update(text).digest("hex");

const buildVersions = [
  "5.5.1.2024-09-07T21:41:32Z",
  "5.5.1.2026-10-13T20:42:55Z",
];
export const normalizeKnownBuildComment = (text, build) =>
  text
    .replaceAll(
      `<!-- Generated by the OWL API (version ${buildVersions[build]}) https://github.com/owlcs/owlapi/ -->`,
      "<!-- Recorded OWL API build version -->",
    )
    .replaceAll(
      `###  Generated by the OWL API (version ${buildVersions[build]}) https://github.com/owlcs/owlapi/`,
      "###  Recorded OWL API build version",
    );
const classify = (probeId, central, rebuilt) => {
  if (probeId === "ObserveStorageContracts") {
    // This exact row contains bytes from a previous successful save followed by
    // a failing save. Preserve both output fragments and the failure position.
    const normalize = (text, build) =>
      text
        .split("\n")
        .map((line) => {
          if (line.startsWith("RDF/XML Syntax:xml-literal\t"))
            return normalizeKnownBuildComment(line, build);
          const sample =
            /^(\S.*:configuration:(?:two-spaces|no-indent|no-banners|labels|save-ids|anonymous-ids-(?:true|false)|single-anonymous-id-(?:true|false))\t\[(?:true|false), )([A-Za-z0-9+/=]+)\]$/u.exec(
              line,
            );
          if (!sample) return line;
          const document = Buffer.from(sample[2], "base64");
          if (document.toString("base64") !== sample[2]) return line;
          return `${sample[1]}${Buffer.from(normalizeKnownBuildComment(document.toString("utf8"), build)).toString("base64")}]`;
        })
        .join("\n");
    if (normalize(central, 0) === normalize(rebuilt, 1))
      return ["generated-build-version-comment"];
  }
  if (probeId === "ObserveParserSelection") {
    const normalize = (text) => {
      const lines = text.split("\n");
      const factories = lines.filter((line) =>
        line.startsWith("parser-factory\t"),
      );
      const priorities = factories.map((line) => Number(line.split("\t")[2]));
      if (
        !factories.length ||
        priorities.some(
          (value, index) =>
            !Number.isFinite(value) ||
            (index > 0 && value < priorities[index - 1]),
        )
      )
        return undefined;
      return [
        ...factories.sort(),
        ...lines.filter((line) => !line.startsWith("parser-factory\t")),
      ].join("\n");
    };
    const left = normalize(central);
    if (left !== undefined && left === normalize(rebuilt))
      return ["parser-priority-tie-order"];
  }
  return [];
};

/** Compare all behavioral rows, retaining provenance rows separately. A file
 * location can differ between Central and the source build; an outcome cannot.
 * This deliberately does not generalize exception, callback or numeric values.
 */
export function compareBehaviorObservations(central, rebuilt) {
  if (
    !central.observations.length ||
    central.observations.length !== rebuilt.observations.length
  )
    throw new Error("Oracle observation coverage differs or is empty");
  const rows = (observation) => {
    const lines = observation.stdout
      .split("\n")
      .filter((line) => !provenanceRows.has(line.split("\t", 1)[0]));
    // getSupportedSettings() returns a collection without a specified order.
    // These rows inventory setting names/values; they are not callback events.
    const settings = lines
      .filter((line) => line.startsWith("rio-setting\t"))
      .sort();
    const behavioralRows = [
      ...lines.filter((line) => !line.startsWith("rio-setting\t")),
      ...settings,
    ].join("\n");
    if (!behavioralRows.trim())
      throw new Error("Oracle emitted no behavioral rows");
    return behavioralRows;
  };
  return central.observations.map((observation, index) => {
    const counterpart = rebuilt.observations[index];
    if (
      observation.probeId !== counterpart.probeId ||
      observation.sourceSha256 !== counterpart.sourceSha256 ||
      JSON.stringify(observation.arguments) !==
        JSON.stringify(counterpart.arguments) ||
      observation.exitCode !== 0 ||
      counterpart.exitCode !== 0
    )
      throw new Error("Oracle subjects, inputs or execution status differ");
    const centralRows = rows(observation);
    const rebuiltRows = rows(counterpart);
    const centralBehaviorSha256 = digest(centralRows);
    const rebuiltBehaviorSha256 = digest(rebuiltRows);
    const identical = centralBehaviorSha256 === rebuiltBehaviorSha256;
    const classifiedDifferences = identical
      ? []
      : classify(observation.probeId, centralRows, rebuiltRows);
    return {
      probeId: observation.probeId,
      arguments: observation.arguments,
      centralBehaviorSha256,
      rebuiltBehaviorSha256,
      areBehavioralObservationsIdentical: identical,
      comparisonStatus: identical
        ? "identical"
        : classifiedDifferences.length
          ? "classified-differences"
          : "unresolved",
      classifiedDifferences,
    };
  });
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(resolve(process.argv[1])).href
) {
  const [centralPath, sourcePath, outputPath] = process.argv.slice(2);
  if (!centralPath || !sourcePath || !outputPath)
    throw new Error(
      "Expected Central observations, source observations and output paths",
    );
  const rows = compareBehaviorObservations(
    JSON.parse(readFileSync(centralPath)),
    JSON.parse(readFileSync(sourcePath)),
  );
  writeFileSync(outputPath, JSON.stringify(rows, null, 2) + "\n");
  process.stdout.write(
    JSON.stringify({
      observationCount: rows.length,
      unresolvedCount: rows.filter(
        ({ comparisonStatus }) => comparisonStatus === "unresolved",
      ).length,
    }) + "\n",
  );
}
