import { compareSelectedParity } from "./compare-selected-parity.mjs";
const input = (rows) => ({
  ontologyInputSha256: "a".repeat(64),
  observations: [
    {
      probeId: "RunRC2Search",
      sourceSha256: "b".repeat(64),
      arguments: [],
      exitCode: 0,
      matchesExpectedCompletion: true,
      stdout: "",
      outputs: [
        {
          name: "search.json",
          content: JSON.stringify({ observations: rows }),
        },
      ],
    },
  ],
});

const storage = (content) => ({
  ...input([]),
  classpathEntries: [
    { name: "owlapi-distribution-5.5.1.jar", sha256: "c".repeat(64) },
  ],
  observations: [
    {
      ...input([]).observations[0],
      probeId: "RunRC2Storage",
      outputs: [{ name: "ontology.ttl", content }],
    },
  ],
});
const releasedComment =
  "###  Generated by the OWL API (version 5.5.1.2024-09-07T21:41:32Z) https://github.com/owlcs/owlapi/";

test("same-release JDK comparison preserves identical build comments and rejects changed bytes", () => {
  const left = storage(releasedComment);
  expect(
    compareSelectedParity(left, storage(releasedComment), {
      sameRelease: true,
    })[0].areSelectedResultsEquivalent,
  ).toBe(true);
  for (const changed of [
    releasedComment.replace("2024", "2026"),
    releasedComment + "\n<urn:a> <urn:p> <urn:b> .",
  ])
    expect(
      compareSelectedParity(left, storage(changed), { sameRelease: true })[0]
        .areSelectedResultsEquivalent,
    ).toBe(false);
});

test.each([
  undefined,
  [],
  [{ name: "owlapi-distribution-5.5.1.jar", sha256: "d".repeat(64) }],
])(
  "same-release comparison rejects changed or absent artifact identity %j",
  (classpathEntries) => {
    const right = { ...storage(releasedComment), classpathEntries };
    expect(() =>
      compareSelectedParity(storage(releasedComment), right, {
        sameRelease: true,
      }),
    ).toThrow("classpath");
  },
);
test("independent invocation ordering is neutral, while result and callback order are preserved", () => {
  const a = {
    method: "getAnnotations",
    argument: { kind: "IRI", iri: "urn:a" },
    repeated: false,
    filtered: true,
    results: ["first", "second"],
  };
  const b = {
    method: "getSuperClasses",
    argument: { kind: "Class", iri: "urn:b" },
    results: [],
  };
  expect(
    compareSelectedParity(input([a, b]), input([b, a]))[0]
      .areSelectedResultsEquivalent,
  ).toBe(true);
  expect(
    compareSelectedParity(
      input([a, b]),
      input([{ ...a, results: ["second", "first"] }, b]),
    )[0].areSelectedResultsEquivalent,
  ).toBe(false);
  expect(() => compareSelectedParity(input([a, b]), input([a, a]))).toThrow(
    /Ambiguous/,
  );
});
