import { readFileSync } from "node:fs";
import { compareBehaviorObservations } from "./compare-behavior-observations.mjs";

const readObservation = (name) =>
  JSON.parse(
    readFileSync(
      new URL(
        `../../docs/compatibility/profiles/java-owlapi-5.5.1/${name}-observations.json`,
        import.meta.url,
      ),
      "utf8",
    ),
  );

test("every retained Central and source-build observation is identical or explicitly classified", () => {
  const result = compareBehaviorObservations(
    readObservation("central"),
    readObservation("source"),
  );
  expect(result).toHaveLength(28);
  expect(result.filter((row) => row.comparisonStatus === "unresolved")).toEqual(
    [],
  );
  expect(
    result
      .filter((row) => !row.areBehavioralObservationsIdentical)
      .every((row) => row.classifiedDifferences.length > 0),
  ).toBe(true);
});

test("a changed callback, outcome or missing probe cannot be admitted as equivalent", () => {
  const central = readObservation("central");
  const rebuilt = readObservation("source");
  const stateProbe = rebuilt.observations.find(
    (row) => row.probeId === "GAP-P01",
  );
  expect(stateProbe.stdout).toContain("begin:3:0");
  stateProbe.stdout = stateProbe.stdout.replace("begin:3:0", "begin:2:0");
  expect(
    compareBehaviorObservations(central, rebuilt).find(
      (row) => row.probeId === "GAP-P01",
    ).comparisonStatus,
  ).toBe("unresolved");
  rebuilt.observations.pop();
  expect(() => compareBehaviorObservations(central, rebuilt)).toThrow(
    /coverage/,
  );
});

test("provenance-only or empty outputs do not prove behavioral equivalence", () => {
  const central = readObservation("central");
  const rebuilt = readObservation("source");
  central.observations[0].stdout = "runtime\t25\n";
  rebuilt.observations[0].stdout = "runtime\t25\n";
  expect(() => compareBehaviorObservations(central, rebuilt)).toThrow(
    /behavioral rows/,
  );
});

const record = (probeId, stdout) => ({
  observations: [
    {
      probeId,
      stdout,
      sourceSha256: "a".repeat(64),
      arguments: [],
      exitCode: 0,
    },
  ],
});
test("only permutations within equal native parser priorities are classified", () => {
  const central = record(
    "ObserveParserSelection",
    "parser-factory\tA\t0\nparser-factory\tB\t9\nparser-factory\tC\t9\nempty\tRETURN\tTurtle\t0\n",
  );
  const permuted = record(
    "ObserveParserSelection",
    "parser-factory\tA\t0\nparser-factory\tC\t9\nparser-factory\tB\t9\nempty\tRETURN\tTurtle\t0\n",
  );
  expect(compareBehaviorObservations(central, permuted)[0]).toMatchObject({
    areBehavioralObservationsIdentical: false,
    comparisonStatus: "classified-differences",
    classifiedDifferences: ["parser-priority-tie-order"],
  });
  const wrongOrder = record(
    "ObserveParserSelection",
    "parser-factory\tB\t9\nparser-factory\tA\t0\nparser-factory\tC\t9\nempty\tRETURN\tTurtle\t0\n",
  );
  expect(
    compareBehaviorObservations(central, wrongOrder)[0].comparisonStatus,
  ).toBe("unresolved");
  permuted.observations[0].stdout = permuted.observations[0].stdout.replace(
    "RETURN",
    "THROW",
  );
  expect(
    compareBehaviorObservations(central, permuted)[0].comparisonStatus,
  ).toBe("unresolved");
});

test("only the known generated build comment is classified inside storage failure bytes", () => {
  const prefix =
    "RDF/XML Syntax:xml-literal\t[OWLOntologyStorageException, prefix ";
  const comment = (version) =>
    `<!-- Generated by the OWL API (version ${version}) https://github.com/owlcs/owlapi/ -->`;
  const central = record(
    "ObserveStorageContracts",
    prefix + comment("5.5.1.2024-09-07T21:41:32Z") + " suffix]",
  );
  const rebuilt = record(
    "ObserveStorageContracts",
    prefix + comment("5.5.1.2026-10-13T20:42:55Z") + " suffix]",
  );
  expect(compareBehaviorObservations(central, rebuilt)[0]).toMatchObject({
    areBehavioralObservationsIdentical: false,
    comparisonStatus: "classified-differences",
    classifiedDifferences: ["generated-build-version-comment"],
  });
  rebuilt.observations[0].stdout = rebuilt.observations[0].stdout.replace(
    "prefix",
    "changed output",
  );
  expect(
    compareBehaviorObservations(central, rebuilt)[0].comparisonStatus,
  ).toBe("unresolved");
});

test("encoded writer samples classify only known build comments, retaining configuration and document differences", () => {
  const sample = (version, literal = "original") =>
    record(
      "ObserveStorageContracts",
      `OWL/XML Syntax:configuration:two-spaces\t[false, ${Buffer.from(`<Literal>${literal}</Literal><!-- Generated by the OWL API (version ${version}) https://github.com/owlcs/owlapi/ -->`).toString("base64")}]`,
    );
  const central = sample("5.5.1.2024-09-07T21:41:32Z");
  expect(
    compareBehaviorObservations(
      central,
      sample("5.5.1.2026-10-13T20:42:55Z"),
    )[0].comparisonStatus,
  ).toBe("classified-differences");
  expect(
    compareBehaviorObservations(
      central,
      sample("5.5.1.2026-10-13T20:42:55Z", "changed"),
    )[0].comparisonStatus,
  ).toBe("unresolved");
});
