const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

/** Only these bounded, reviewed distinctions may differ in this shared fixture. */
export const compareRdfXmlPresentation = (javaText, javascriptText, mode) => {
  const normalize = (text, java) => {
    let normalized = text.replaceAll("\r\n", "\n");
    normalized = normalized.replace(
      /^<\?xml version="1\.0"(?: encoding="UTF-8")?\?>/u,
      '<?xml version="1.0"?>',
    );
    normalized = normalized.replace(
      java
        ? /<!-- Generated by the OWL API \(version 5\.5\.1\) https:\/\/github\.com\/owlcs\/owlapi\/ -->/u
        : /<!-- Generated by @hadden-industries\/owlapi \(JavaScript implementation; version 0\.1\.0-rc\.1\) https:\/\/github\.com\/Hadden-Industries\/owlapi -->/u,
      "<!-- Generator attribution -->",
    );
    if (java) {
      normalized = normalized.replace(
        /<rdf:Description((?: rdf:nodeID="[^"]+")?)>\n([ ]*)<rdf:type rdf:resource="http:\/\/www\.w3\.org\/2002\/07\/owl#AllDifferent"\/>\n([\s\S]*?<owl:distinctMembers[\s\S]*?<\/owl:distinctMembers>)\n([ ]*)<\/rdf:Description>/u,
        (_, attributes, _indentation, members, closingIndentation) =>
          `<owl:AllDifferent${attributes}>\n${members.replaceAll("owl:distinctMembers", "owl:members")}\n${closingIndentation}</owl:AllDifferent>`,
      );
      // Java 5.5.1 emits this one general-axiom banner even when banners are off.
      if (mode === "no-banners")
        normalized = normalized.replace(
          /\n {4}\n\n\n {4}<!-- \n {4}\/{87}\n {4}\/\/\n {4}\/\/ General axioms\n {4}\/\/\n {4}\/{87}\n {5}-->\n\n\n/u,
          "\n",
        );
    }
    const identifiers = new Map();
    return normalized.replaceAll(/rdf:nodeID="([^"]+)"/gu, (_, identifier) => {
      if (!identifiers.has(identifier))
        identifiers.set(identifier, identifiers.size);
      return `rdf:nodeID="anonymous${identifiers.get(identifier)}"`;
    });
  };
  const java = normalize(javaText, true);
  const javascript = normalize(javascriptText, false);
  const firstDifferentLine = java
    .split("\n")
    .findIndex((line, index) => line !== javascript.split("\n")[index]);
  return {
    matches: java === javascript,
    firstDifferentLine: firstDifferentLine < 0 ? null : firstDifferentLine + 1,
  };
};

/** DOM owns XML syntax; this probe records only writer presentation facts. */
export const observeRdfXmlPresentation = (text) => {
  const document = new DOMParser().parseFromString(text, "application/xml");
  const root = document.documentElement;
  const elements = Array.from(root.childNodes).filter(
    (node) => node.nodeType === 1,
  );
  const iri = (node) => node.getAttributeNS(rdf, "about");
  const rootTag = text.slice(
    text.indexOf("<" + root.nodeName),
    text.indexOf(">", text.indexOf("<" + root.nodeName)) + 1,
  );
  return {
    namespaces: Object.fromEntries(
      Array.from(root.attributes)
        .filter((attribute) => attribute.namespaceURI === xmlns)
        .map((attribute) => [attribute.name, attribute.value]),
    ),
    base: root.getAttributeNS(xml, "base"),
    rootAttributeIndentation: rootTag
      .split("\n")
      .slice(1)
      .map((line) => line.match(/^ */u)[0].length),
    entities: elements
      .filter((node) => iri(node))
      .map((node) => ({
        iri: iri(node),
        type: node.namespaceURI + node.localName,
        properties: Array.from(node.childNodes)
          .filter((child) => child.nodeType === 1)
          .map((child) => child.namespaceURI + child.localName),
      })),
    comments: Array.from(root.childNodes)
      .filter((node) => node.nodeType === 8)
      .map((node) => node.data.trim()),
    anonymousIds: Array.from(document.getElementsByTagName("*")).filter(
      (node) => node.hasAttributeNS(rdf, "nodeID"),
    ).length,
    stringDatatypes: Array.from(document.getElementsByTagName("*")).filter(
      (node) =>
        node.getAttributeNS(rdf, "datatype") ===
        "http://www.w3.org/2001/XMLSchema#string",
    ).length,
  };
};

/** Reuses the pinned launcher and Java structural oracle; adds layout probes only. */
export const runWriterConfigurationContract = async ({ outputDirectory }) => {
  const output = resolve(outputDirectory);
  await mkdir(output, { recursive: false });
  const environment = await resolvePinnedReferenceEnvironment();
  const extended = {
    ...environment,
    oracleSources: [
      ...environment.oracleSources,
      join(referenceDirectory, "RunWriterConfigurationContract.java"),
    ],
  };
  const classes = join(output, "classes");
  const compilation = await compileOntologyReferenceOracles(extended, classes);
  await writeFile(join(output, "compile.log"), compilation.stderr);
  const input = join(
    referenceDirectory,
    "fixtures/storage/rdfxml-refinements.ofn",
  );
  const source = await readFile(input, "utf8");
  const javaDirectory = join(output, "java");
  const javaRun = await executeFile(
    "java",
    [
      "-cp",
      classes,
      "RunWithClasspath",
      environment.classpathFile,
      classes,
      "RunWriterConfigurationContract",
      input,
      javaDirectory,
    ],
    { encoding: "utf8", maxBuffer: 8 * 1024 * 1024 },
  );
  await writeFile(join(output, "java.log"), javaRun.stdout + javaRun.stderr);
  const javascriptDirectory = join(output, "javascript");
  await mkdir(javascriptDirectory);
  const observations = [];
  for (const mode of modes) {
    const manager = OWLManager.createOWLOntologyManager();
    const ontology = await manager.loadOntologyFromOntologyDocument(
      new StringDocumentSource(source, { format: "functional" }),
    );
    let configuration = new OWLOntologyWriterConfiguration();
    if (mode === "no-banners")
      configuration = configuration.withBannersEnabled(false);
    if (mode === "two-spaces") configuration = configuration.withIndentSize(2);
    if (mode === "no-indent")
      configuration = configuration.withIndenting(false);
    if (mode === "labels")
      configuration = configuration.withLabelsAsBanner(true);
    if (mode === "save-ids")
      configuration = configuration.withSaveIdsForAllAnonymousIndividuals(true);
    manager.setOntologyWriterConfiguration(configuration);
    let format = new RDFXMLDocumentFormat();
    format.setDefaultPrefix("urn:refinement:");
    format.setPrefix("schema:", "http://schema.org/");
    format.setPrefix("unused:", "urn:unused:");
    if (mode === "force-string")
      format = format.withParameter("force xsd:string on literals", true);
    const target = new StringDocumentTarget();
    await manager.saveOntology(ontology, format, target);
    const text = target.toString();
    const path = join(javascriptDirectory, `${mode}.rdf`);
    await writeFile(path, text);
    const javaText = await readFile(join(javaDirectory, `${mode}.rdf`), "utf8");
    const structural = await executeOntologyParsingOracle(
      {
        catalogMappings: [],
        compiledOracleDirectory: classes,
        rootPath: input,
        sourceDocumentPath: input,
        verifyOutputPath: path,
      },
      environment,
    );
    await writeFile(
      join(output, `${mode}-structural.json`),
      JSON.stringify(structural, null, 2) + "\n",
    );
    observations.push({
      mode,
      javaSha256: sha256(javaText),
      javascriptSha256: sha256(text),
      java: observeRdfXmlPresentation(javaText),
      javascript: observeRdfXmlPresentation(text),
      presentation: compareRdfXmlPresentation(javaText, text, mode),
      structural,
    });
  }
  const report = {
    schemaVersion: 1,
    pinnedRevision: environment.pinnedRevision,
    owlapiVersion: environment.owlapiVersion,
    inputSha256: sha256(source),
    observations,
  };
  await writeFile(
    join(output, "report.json"),
    JSON.stringify(report, null, 2) + "\n",
  );
  return report;
};

if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
) {
  const report = await runWriterConfigurationContract({
    outputDirectory: process.argv[2],
  });
  console.log(
    JSON.stringify({
      outputDirectory: resolve(process.argv[2]),
      modes: report.observations.map(({ mode, presentation, structural }) => ({
        mode,
        presentation,
        structuralExitCode: structural.exitCode,
      })),
    }),
  );
  if (
    report.observations.some(
      ({ presentation, structural }) =>
        !presentation.matches || structural.exitCode !== 0,
    )
  )
    process.exitCode = 1;
}
