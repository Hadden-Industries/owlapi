import { readFileSync, writeFileSync } from "node:fs";
import { format, resolveConfig } from "prettier";

// Public constant observations are data, not a translation of Java control flow.
// The independent profile verdicts remain test inputs and are never generated here.
const input = new URL(
  "../../docs/compatibility/profiles/java-owlapi-5.5.1/central-observations.json",
  import.meta.url,
);
const output = new URL(
  "../../internal/behavior/javaDatatypePolicy.js",
  import.meta.url,
);
const observation = JSON.parse(readFileSync(input, "utf8")).observations.find(
  ({ probeId }) => probeId === "ObserveLanguageProfileSemantics",
);
if (!observation || observation.exitCode !== 0)
  throw new Error("Missing successful native datatype observation");
const records = new Map();
for (const line of observation.stdout.split("\n")) {
  const [kind, iri, value] = line.split("\t");
  if (kind === "datatype-pattern") records.set(iri, { pattern: value });
  if (kind === "datatype-facets") {
    if (!records.has(iri)) throw new Error(`Missing pattern for ${iri}`);
    records.get(iri).facets = value ? value.split(" ") : [];
  }
}
if (records.size !== 35 || [...records.values()].some(({ facets }) => !facets))
  throw new Error("Incomplete Java datatype constants");
const source = `// Generated by util/owlapi-reference/generate-java-datatype-policy.mjs.\n// Public OWLAPI 5.5.1 OWL2Datatype getter observations; see the profile provenance.\n// These patterns intentionally preserve the released implementation's semantics.\nconst definitions = ${JSON.stringify(Object.fromEntries(records))};\nfor (const definition of Object.values(definitions)) { Object.freeze(definition.facets); Object.freeze(definition); }\nexport const javaDatatypeDefinitions = Object.freeze(definitions);\n`;
writeFileSync(
  output,
  await format(source, {
    ...(await resolveConfig(output.pathname)),
    parser: "babel",
  }),
);
