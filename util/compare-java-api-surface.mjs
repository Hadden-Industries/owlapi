import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import { resolve } from "node:path";
import { isDeepStrictEqual } from "node:util";
import { format } from "prettier";
import { publicMembers } from "./public-api-members.mjs";

export const PUBLISHED_RC2_SOURCE = "d3f9fdba5ac1409346bf0c59512e3cf23a3c1517";
const root = fileURLToPath(new URL("../", import.meta.url));
const registryPath = "docs/compatibility/java-api-surface.json";
const outputPath = "docs/compatibility/0.1.0-api-delta.md";
const digest = (bytes) => createHash("sha256").update(bytes).digest("hex");
// Interpret the historical schema without rewriting immutable release artifacts.
const normalizeBinding = ({ firstPublicRelease, ...binding }) =>
  firstPublicRelease === undefined
    ? binding
    : { ...binding, firstPublicReleaseTarget: firstPublicRelease };
const codeList = (values) =>
  values.length ? values.map((value) => `\`${value}\``).join(", ") : "none";

/** Both inputs are generator-owned registries; this creates no member whitelist. */
export const compareSurface = (before, after) => {
  const previous = new Map(
    before.bindings.map((binding) => [binding.id, normalizeBinding(binding)]),
  );
  const current = new Map(
    after.bindings.map((binding) => [binding.id, binding]),
  );
  return {
    added: after.bindings.filter((binding) => !previous.has(binding.id)),
    removed: before.bindings.filter((binding) => !current.has(binding.id)),
    changed: after.bindings.flatMap((binding) => {
      const prior = previous.get(binding.id);
      if (!prior) return [];
      const fields = Object.keys(binding).filter(
        (key) => !isDeepStrictEqual(binding[key], prior[key]),
      );
      return fields.length
        ? [
            {
              binding,
              prior,
              fields,
              added: binding.supportedMembers.filter(
                (member) => !prior.supportedMembers.includes(member),
              ),
              removed: prior.supportedMembers.filter(
                (member) => !binding.supportedMembers.includes(member),
              ),
            },
          ]
        : [];
    }),
  };
};

const main = async () => {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== "--write"))
    throw new Error(
      "Expected --write or no arguments for comparison checking.",
    );
  const beforeBytes = execFileSync(
    "git",
    ["show", `${PUBLISHED_RC2_SOURCE}:${registryPath}`],
    {
      cwd: root,
      timeout: 15000,
      maxBuffer: 8 * 1024 * 1024,
      windowsHide: true,
    },
  );
  const afterBytes = await readFile(resolve(root, registryPath));
  const before = JSON.parse(beforeBytes),
    after = JSON.parse(afterBytes);
  const delta = compareSurface(before, after);
  const coverageBytes = await readFile(
    resolve(root, "docs/performance/java-api-benchmark-coverage.json"),
  );
  const coverage = JSON.parse(coverageBytes);
  const lines = [
    "<!-- Generated by util/compare-java-api-surface.mjs; edit owning API metadata, not this inventory. -->",
    "# Published rc.2 to current 0.1.0 implementation: API inventory",
    "",
    `Published source: \`${PUBLISHED_RC2_SOURCE}\`; registry SHA-256 \`${digest(beforeBytes)}\`.`,
    `Current registry SHA-256: \`${digest(afterBytes)}\`. The current package version field is not evidence of publication.`,
    `Performance coverage SHA-256: \`${digest(coverageBytes)}\`. Historical \`firstPublicRelease\` fields are interpreted as \`firstPublicReleaseTarget\`; this schema rename alone is not an API change.`,
    "Run the API generator first, then `node util/compare-java-api-surface.mjs --write`; comparison requires the published source object locally and is not a shallow-CI prerequisite.",
    "",
    `Namespaces: ${before.summary.namespaceCount} → ${after.summary.namespaceCount}; bindings: ${before.bindings.length} → ${after.bindings.length}.`,
    `Added exports: ${delta.added.length}; removed exports: ${delta.removed.length}.`,
    "",
    "The registry now includes inherited library members. An added inventory entry for an inherited member corrects documentation and does not establish a newly implemented method. Native Object/Function/Error methods are excluded.",
    "The [behavior profile contract](behavior-profiles.md) owns defaults, return shapes, errors, mutation timing and host boundaries. The [scope reconciliation](0.1.0-contract-scope.md) separates the supported source assessment from incomplete future work.",
    "",
    "## Added exports",
    "",
  ];
  for (const binding of delta.added)
    lines.push(
      `### ${binding.id}`,
      "",
      `Specifier: \`${binding.publicSpecifier}\`.`,
      `Members: ${codeList(binding.supportedMembers)}.`,
      `Call shapes: ${codeList(binding.callShapes)}.`,
      `Public errors: ${codeList(binding.publicErrors)}. This field lists named API errors, not every possible host failure.`,
      ...binding.semanticQualifications.map((text) => `- ${text}`),
      "",
      `Functional evidence owners: ${codeList(binding.verification)}.`,
      "",
    );
  lines.push("## Existing export changes", "");
  for (const { binding, fields, added, removed } of delta.changed) {
    const module = await import(
      pathToFileURL(resolve(root, binding.sourceModule)).href
    );
    const own = publicMembers(module[binding.jsExport], { inherited: false });
    lines.push(
      `### ${binding.id}`,
      "",
      `New directly declared member records: ${codeList(added.filter((member) => own.includes(member)))}.`,
      `Newly recorded inherited members: ${codeList(added.filter((member) => !own.includes(member)))}.`,
      `Removed member records: ${codeList(removed)}.`,
      `Changed registry fields: ${codeList(fields)}.`,
      "",
      ...binding.semanticQualifications.map((text) => `- ${text}`),
      "",
    );
  }
  lines.push(
    "## Complete member performance disposition",
    "",
    "Each row comes from the current authoritative member inventory. Exact benchmark symbol matches identify grouped measurements, not exhaustive overload or semantic admission. The retained coverage file states each group's comparability; checksum-only rows remain unqualified for full parity. A class-level benchmark is not assigned to unmeasured individual members.",
    "Members without an exact workload match have functional-only release coverage through their binding's verification owners; this is an explicit lack of a member-specific performance claim. Further performance work is required if such a member is made a release performance promise. Both behavior profiles remain subject to their documented contracts.",
    "",
    "| Binding/member | Exact grouped workloads or disposition | Functional evidence owners |",
    "| --- | --- | --- |",
  );
  for (const binding of after.bindings)
    for (const member of binding.supportedMembers) {
      const name = member.replace(/^(?:prototype\.|static )/u, "");
      const symbol =
        member === "constructor"
          ? binding.jsExport
          : `${binding.jsExport}.${name}`;
      const matches = coverage.cases.filter((row) =>
        row.apiSymbols.includes(symbol),
      );
      lines.push(
        `| \`${binding.id}: ${member}\` | ${matches.length ? matches.map((row) => `\`${row.id}\` (${row.comparability.status})`).join("; ") : "Functional-only; no member-specific timing claim"} | ${codeList(binding.verification)} |`,
      );
    }
  const expected = await format(lines.join("\n") + "\n", {
    parser: "markdown",
    proseWrap: "preserve",
    endOfLine: "lf",
  });
  if (args[0] === "--write")
    await writeFile(resolve(root, outputPath), expected);
  else if ((await readFile(resolve(root, outputPath), "utf8")) !== expected)
    throw new Error(
      "Published API delta is stale; regenerate after the authoritative registry.",
    );
  process.stdout.write(
    `${args[0] === "--write" ? "Wrote" : "Verified"} ${outputPath}: ${delta.added.length} added exports, ${delta.removed.length} removed, ${delta.changed.length} changed bindings.\n`,
  );
};

if (
  process.argv[1] &&
  pathToFileURL(resolve(process.argv[1])).href === import.meta.url
)
  await main();
