/** Exercise the real scanner and repository normalizer against independent 3.14 observations. */
import { execFile } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs, promisify } from "node:util";
import { prepareScancode } from "./prepare-scancode.mjs";
import { downloadLockedRegistryTarball } from "./acquire-npm-package-evidence.mjs";
import {
  inspectPackageTarball,
  materializePackageForScan,
} from "./third-party-evidence/archive-evidence.mjs";
import {
  sha256,
  stableJson,
  verifySha512Sri,
} from "./third-party-evidence/digests.mjs";
import { normalizeLockedRegistryGraph } from "./third-party-evidence/lock-graph.mjs";
import {
  buildScancodeArguments,
  normalizeScancodeReport,
  SCANCODE_PRE_SCAN_EXCLUDED_FILE_SUFFIXES,
} from "./third-party-evidence/scancode.mjs";

const executeFile = promisify(execFile);
const repositoryRoot = fileURLToPath(new URL("../", import.meta.url));

/** Qualify a fresh locked installation; retain raw reports and failures for diagnosis. */
export async function qualifyScancodeRuntime({
  python,
  outputRoot = ".release/scancode-qualification",
} = {}) {
  outputRoot = resolve(repositoryRoot, outputRoot);
  await mkdir(dirname(outputRoot), { recursive: true });
  await mkdir(outputRoot, { recursive: false });
  const reports = join(outputRoot, "reports");
  const inputs = join(outputRoot, "inputs");
  await mkdir(reports);
  await mkdir(inputs);
  const baselineBytes = await readFile(
    new URL("./scancode-runtime/qualification-baseline.json", import.meta.url),
  );
  const baseline = JSON.parse(baselineBytes);
  let prepared;
  try {
    prepared = await prepareScancode({
      platform: process.platform === "win32" ? "windows" : "linux",
      outputRoot: join(outputRoot, "tools"),
      python,
    });
  } catch (error) {
    await writeFile(
      join(reports, "installation-failure.log"),
      `${error.stdout ?? ""}${error.stderr ?? ""}\n${error.stack ?? error.message}\n`,
    );
    throw error;
  }
  await writeFile(
    join(reports, "installation.json"),
    stableJson({ ...prepared, baselineSha256: sha256(baselineBytes) }),
  );
  // ScanCode retains the input basename in nested licence-reference fields.
  // Preserve the independent oracle's directory names as fixture preconditions.
  const representative = join(inputs, "scan-fixture");
  await mkdir(join(representative, "_optPlug.node"), { recursive: true });
  // These exact bytes were scanned by the independently authenticated official
  // 3.14 distribution. Changing them requires a reviewed baseline refresh.
  const files = {
    LICENSE: await readFile(join(repositoryRoot, "LICENSE")),
    "package.json": JSON.stringify(
      {
        name: "@owlapi-probe/license-fixture",
        version: "1.0.0",
        license: "AGPL-3.0-only",
        author: "OwlAPI Compatibility Fixture",
        dependencies: { "example-dependency": "^1.0.0" },
      },
      null,
      2,
    ),
    "_optPlug.node/source.js":
      '// SPDX-License-Identifier: MIT\n// Copyright (c) 2026 OwlAPI Compatibility Fixture\nexport const greeting = "hello";\n',
    "generated.js":
      "// Code generated by fixture generator. DO NOT EDIT.\n// SPDX-License-Identifier: Apache-2.0\nexport const generated = true;\n",
    NOTICE:
      "SPDX-License-Identifier: LicenseRef-OwlAPI-Compatibility-Unknown\nCopyright (c) 2026 OwlAPI Compatibility Fixture\nPermission to use this software is granted only when the user sends an orange postcard to the original author.\nAll other uses are prohibited. This software is provided without warranty.\n",
  };
  for (const [name, bytes] of Object.entries(files))
    await writeFile(join(representative, name), bytes);
  await writeFile(
    join(reports, "representative-inputs.json"),
    stableJson(
      Object.entries(files).map(([name, bytes]) => ({
        name,
        sha256: sha256(bytes),
        size: Buffer.byteLength(bytes),
      })),
    ),
  );

  const lockfileBytes = await readFile(
    join(repositoryRoot, "package-lock.json"),
  );
  const graph = normalizeLockedRegistryGraph(lockfileBytes);
  const expectedN3 = baseline.cases.find(({ id }) => id === "n3");
  const identity = graph.artifacts.find(
    ({ name, version, integrity }) =>
      name === expectedN3.name &&
      version === expectedN3.version &&
      integrity === expectedN3.integrity,
  );
  if (!identity)
    throw new Error(
      "Locked N3 identity differs from the reviewed scanner qualification baseline",
    );
  const tarball = join(inputs, "n3.tgz");
  await downloadLockedRegistryTarball({
    identity,
    destination: tarball,
    cache: join(outputRoot, "cache"),
  });
  verifySha512Sri(await readFile(tarball), identity.integrity);
  const inventory = await inspectPackageTarball(tarball, identity);
  const n3 = join(inputs, "n3-fixture");
  await materializePackageForScan(tarball, inventory, n3, {
    excludedFileSuffixes: SCANCODE_PRE_SCAN_EXCLUDED_FILE_SUFFIXES,
  });
  await writeFile(
    join(reports, "n3-inputs.json"),
    stableJson({
      identity,
      lockfileSha256: sha256(lockfileBytes),
      entries: inventory.entries,
    }),
  );

  const results = [];
  for (const expected of baseline.cases) {
    const inputRoot = expected.id === "representative" ? representative : n3;
    const outputPath = join(reports, `${expected.id}-raw.json`);
    const args = buildScancodeArguments({ inputRoot, outputPath });
    let execution;
    try {
      execution = await executeFile(prepared.command, args, {
        cwd: repositoryRoot,
        timeout: 10 * 60_000,
        maxBuffer: 32 * 1024 * 1024,
        windowsHide: true,
        shell: false,
        env: Object.fromEntries(
          Object.entries(process.env).filter(
            ([name]) => !/^(?:UV_|PIP_|PYTHON|VIRTUAL_ENV$)/iu.test(name),
          ),
        ),
      });
    } catch (error) {
      await writeFile(
        join(reports, `${expected.id}-execution.log`),
        `${error.stdout ?? ""}${error.stderr ?? ""}\n${error.stack}\n`,
      );
      throw error;
    }
    await writeFile(
      join(reports, `${expected.id}-execution.log`),
      execution.stdout + execution.stderr,
    );
    const normalized = normalizeScancodeReport(
      JSON.parse(await readFile(outputPath, "utf8")),
      { artifactId: expected.artifactId, inputRoot },
    );
    const canonical = stableJson(normalized);
    await writeFile(join(reports, `${expected.id}-normalized.json`), canonical);
    const result = {
      id: expected.id,
      files: normalized.files.length,
      sha256: sha256(canonical),
      expectedSha256: expected.expectedSha256,
    };
    results.push(result);
    await writeFile(join(reports, "comparison.json"), stableJson(results));
    if (
      result.files !== expected.fileCount ||
      result.sha256 !== expected.expectedSha256
    )
      throw new Error(
        `ScanCode ${expected.id} findings differ from the independent qualification baseline`,
      );
  }
  return {
    status: "QUALIFIED",
    pythonVersion: prepared.pythonVersion,
    scannerVersion: prepared.scancodeVersion,
    beartypeVersion: prepared.beartypeVersion,
    lockSha256: prepared.lockSha256,
    platform: process.platform,
    results,
  };
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    const { values } = parseArgs({
      options: { "python-env": { type: "string" }, output: { type: "string" } },
      strict: true,
      allowPositionals: false,
    });
    if (!/^[A-Z][A-Z0-9_]*$/u.test(values["python-env"] ?? ""))
      throw new TypeError(
        "Qualification requires --python-env=<environment variable name>",
      );
    const python = process.env[values["python-env"]];
    if (!python)
      throw new TypeError(
        `Qualification Python environment variable ${values["python-env"]} is not set`,
      );
    const outputRoot = values.output;
    const result = await qualifyScancodeRuntime({ python, outputRoot });
    process.stdout.write(stableJson(result));
  } catch (error) {
    process.stderr.write(`${error.stack}\n`);
    process.exitCode = 1;
  }
}
